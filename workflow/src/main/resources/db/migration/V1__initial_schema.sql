-- Initial schema: matches what Hibernate generated from the entities while
-- spring.jpa.hibernate.ddl-auto=update was in use. Foreign key names are the
-- ones Hibernate produced, so they are identical in databases created before
-- Flyway was added.

create table users (
    id         bigint generated by default as identity,
    name       varchar(255),
    email      varchar(255) not null unique,
    password   varchar(255),
    role       varchar(255) check (role in ('ROLE_EMPLOYEE','ROLE_MANAGER','ROLE_ADMIN')),
    created_at timestamp(6),
    primary key (id)
);

create table requests (
    id          bigint generated by default as identity,
    version     bigint,
    title       varchar(255),
    description varchar(255),
    status      varchar(255) check (status in ('PENDING','APPROVED','REJECTED','COMPLETED')),
    employee_id bigint,
    manager_id  bigint,
    created_at  timestamp(6),
    updated_at  timestamp(6),
    primary key (id)
);

create table request_history (
    id              bigint generated by default as identity,
    request_id      bigint,
    actor_id        bigint,
    action          varchar(255) check (action in ('REQUEST_SUBMITTED','REQUEST_APPROVED','REQUEST_REJECTED')),
    previous_status varchar(255) check (previous_status in ('PENDING','APPROVED','REJECTED','COMPLETED')),
    new_status      varchar(255) check (new_status in ('PENDING','APPROVED','REJECTED','COMPLETED')),
    occurred_at     timestamp(6),
    primary key (id)
);

-- AuditLog uses GenerationType.AUTO, so Hibernate takes ids from this sequence
-- in blocks of 50.
create sequence audit_log_seq start with 1 increment by 50;

create table audit_log (
    id             integer not null,
    action         varchar(255),
    request_id     bigint,
    actor_email    varchar(255),
    employee_email varchar(255),
    status         varchar(255) check (status in ('PENDING','APPROVED','REJECTED','COMPLETED')),
    created_at     timestamp(6),
    primary key (id)
);

create table outbox_event (
    id                    bigint generated by default as identity,
    status                varchar(255) check (status in ('PENDING','PROCESSING','FAILED','PROCESSED','PERMANENTLY_FAILED')),
    event_type            varchar(255),
    aggregate_id          bigint,
    payload               jsonb,
    retry_count           integer not null,
    next_retry_at         timestamp(6),
    processing_started_at timestamp(6),
    created_at            timestamp(6),
    processed_at          timestamp(6),
    last_error            varchar(2000),
    primary key (id)
);

